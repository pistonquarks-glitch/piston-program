export function validateProtocolVersion(version: string): boolean {
  return ProtocolVersionSchema.safeParse(version).success;
}

export function validateSchema<T>(schema: z.ZodSchema<T>, data: unknown): { success: true; data: T } | { success: false; error: z.ZodError } {
  const result = schema.safeParse(data);
  if (result.success) {
    return { success: true, data: result.data };
  }
  return { success: false, error: result.error };
}

export type SchemaKey = keyof typeof ProtocolSchemas;

export function getSchema<K extends SchemaKey>(key: K): z.ZodSchema<(typeof ProtocolSchemas)[K]['_output']> {
  return ProtocolSchemas[key] as z.ZodSchema<(typeof ProtocolSchemas)[K]['_output']>;
}

